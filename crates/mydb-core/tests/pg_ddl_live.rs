//! Schema management against a real PostgreSQL server. Skipped unless
//! `MYDB_PG_HOST` is set; see `pg_live.rs` for the other variables.

use mydb_core::ddl::{
    ColumnDesign, ForeignKeyDesign, IndexDesign, IndexKind, IndexPart, ObjectKind, SchemaChange,
    TableDesign,
};
use mydb_core::{ConnectionProfile, PgSession, pg_ddl};

fn env(name: &str) -> Option<String> {
    std::env::var(name).ok().filter(|v| !v.is_empty())
}

fn base_profile() -> Option<ConnectionProfile> {
    let host = env("MYDB_PG_HOST")?;
    let mut p = ConnectionProfile::new_postgres("pg-ddl-test", host);
    p.port = env("MYDB_PG_PORT").map_or(5432, |v| v.parse().unwrap());
    p.user = env("MYDB_PG_USER").unwrap_or("postgres".into());
    p.password = env("MYDB_PG_PASSWORD");
    if let Some(db) = env("MYDB_PG_DATABASE") {
        p.database = Some(db);
    }
    Some(p)
}

async fn session_or_skip(schema: &str) -> Option<PgSession> {
    let Some(p) = base_profile() else {
        eprintln!("MYDB_PG_HOST not set, skipping");
        return None;
    };
    let s = PgSession::connect(&p).await.unwrap();
    let out = s
        .execute(
            &format!(
                "DROP SCHEMA IF EXISTS {schema} CASCADE; CREATE SCHEMA {schema};
                 CREATE TABLE {schema}.items (
                   id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                   name varchar(40) NOT NULL,
                   price numeric(10,2) DEFAULT 0,
                   note text
                 );
                 CREATE UNIQUE INDEX items_name ON {schema}.items (name);
                 COMMENT ON COLUMN {schema}.items.note IS 'free text';
                 INSERT INTO {schema}.items (name, price) VALUES ('a', 1), ('b', 2);"
            ),
            10,
        )
        .await;
    assert!(out.error.is_none(), "{:?}", out.error);
    Some(s)
}

async fn apply_ok(s: &PgSession, change: &SchemaChange) {
    let run = pg_ddl::apply(s, change).await.unwrap();
    assert!(
        run.outcome.error.is_none(),
        "{:?}\n{}",
        run.outcome.error,
        run.sql
    );
}

fn col(name: &str, ty: &str) -> ColumnDesign {
    ColumnDesign {
        name: name.into(),
        column_type: ty.into(),
        nullable: true,
        ..Default::default()
    }
}

#[tokio::test]
async fn reads_a_table_and_an_unchanged_design_plans_nothing() {
    let Some(s) = session_or_skip("d_read").await else {
        return;
    };
    let meta = pg_ddl::meta(&s).await.unwrap();
    assert!(meta.flavor.postgres);

    let d = pg_ddl::table_design(&s, "d_read", "items").await.unwrap();
    let names: Vec<&str> = d.columns.iter().map(|c| c.name.as_str()).collect();
    assert_eq!(names, ["id", "name", "price", "note"]);
    assert!(d.columns[0].auto_increment);
    assert_eq!(d.columns[1].column_type, "character varying(40)");
    assert!(!d.columns[1].nullable);
    assert_eq!(d.columns[2].default.as_deref(), Some("0"));
    assert_eq!(d.columns[3].comment, "free text");
    let pk = d
        .indexes
        .iter()
        .find(|i| i.kind == IndexKind::Primary)
        .unwrap();
    assert_eq!(pk.parts[0].column, "id");
    assert!(
        d.indexes
            .iter()
            .any(|i| i.name == "items_name" && i.kind == IndexKind::Unique)
    );

    let plan = pg_ddl::plan(
        &s,
        &SchemaChange::AlterTable {
            database: "d_read".into(),
            original: Box::new(d.clone()),
            design: Box::new(d),
            convert_charset: false,
        },
    )
    .await
    .unwrap();
    assert!(plan.statements.is_empty(), "{:?}", plan.statements);
}

#[tokio::test]
async fn alters_creates_and_drops_tables() {
    let Some(s) = session_or_skip("d_alter").await else {
        return;
    };
    let original = pg_ddl::table_design(&s, "d_alter", "items").await.unwrap();
    let mut design = original.clone();
    design.columns[1].name = "title".into();
    design.columns[1].column_type = "varchar(80)".into();
    design.columns[2].default = Some("5".into());
    design.columns[3].nullable = false;
    design.columns[3].default = Some("''".into());
    design.columns.push(col("qty", "integer"));
    design.indexes.push(IndexDesign {
        original: None,
        name: "items_qty".into(),
        kind: IndexKind::Index,
        parts: vec![IndexPart {
            column: "qty".into(),
            descending: true,
            ..Default::default()
        }],
        using: None,
        comment: String::new(),
    });
    design.options.comment = "goods".into();
    // `note` has NULLs: setting NOT NULL fails unless they are filled first,
    // so do that in the same run with a separate statement beforehand.
    s.execute("UPDATE d_alter.items SET note = ''", 0).await;
    apply_ok(
        &s,
        &SchemaChange::AlterTable {
            database: "d_alter".into(),
            original: Box::new(original),
            design: Box::new(design),
            convert_charset: false,
        },
    )
    .await;
    let now = pg_ddl::table_design(&s, "d_alter", "items").await.unwrap();
    let names: Vec<&str> = now.columns.iter().map(|c| c.name.as_str()).collect();
    assert_eq!(names, ["id", "title", "price", "note", "qty"]);
    assert_eq!(now.columns[1].column_type, "character varying(80)");
    assert_eq!(now.columns[2].default.as_deref(), Some("5"));
    assert!(!now.columns[3].nullable);
    assert_eq!(now.options.comment, "goods");
    let qty = now.indexes.iter().find(|i| i.name == "items_qty").unwrap();
    assert!(qty.parts[0].descending);
    // The unique index followed the renamed column.
    let uniq = now.indexes.iter().find(|i| i.name == "items_name").unwrap();
    assert_eq!(uniq.parts[0].column, "title");

    // A new table referencing it.
    let orders = TableDesign {
        name: "orders".into(),
        columns: vec![
            ColumnDesign {
                name: "id".into(),
                column_type: "bigint".into(),
                auto_increment: true,
                ..Default::default()
            },
            ColumnDesign {
                name: "item_id".into(),
                column_type: "integer".into(),
                ..Default::default()
            },
            ColumnDesign {
                name: "at".into(),
                column_type: "timestamptz".into(),
                default: Some("now()".into()),
                ..Default::default()
            },
        ],
        indexes: vec![IndexDesign {
            original: None,
            name: "PRIMARY".into(),
            kind: IndexKind::Primary,
            parts: vec![IndexPart {
                column: "id".into(),
                ..Default::default()
            }],
            using: None,
            comment: String::new(),
        }],
        foreign_keys: vec![ForeignKeyDesign {
            original: None,
            name: "orders_item".into(),
            columns: vec!["item_id".into()],
            ref_database: None,
            ref_table: "items".into(),
            ref_columns: vec!["id".into()],
            on_delete: "CASCADE".into(),
            on_update: String::new(),
        }],
        options: Default::default(),
    };
    apply_ok(
        &s,
        &SchemaChange::CreateTable {
            database: "d_alter".into(),
            design: Box::new(orders),
        },
    )
    .await;
    let read = pg_ddl::table_design(&s, "d_alter", "orders").await.unwrap();
    assert!(read.columns[0].auto_increment);
    assert_eq!(read.foreign_keys.len(), 1);
    assert_eq!(read.foreign_keys[0].on_delete, "CASCADE");
    assert_eq!(read.foreign_keys[0].ref_table, "items");

    // Dropping the referenced table is refused (no CASCADE).
    let run = pg_ddl::apply(
        &s,
        &SchemaChange::DropTable {
            database: "d_alter".into(),
            table: "items".into(),
        },
    )
    .await
    .unwrap();
    assert!(run.outcome.error.is_some());
    apply_ok(
        &s,
        &SchemaChange::DropTable {
            database: "d_alter".into(),
            table: "orders".into(),
        },
    )
    .await;
}

#[tokio::test]
async fn a_failing_change_is_rolled_back() {
    let Some(s) = session_or_skip("d_rollback").await else {
        return;
    };
    let original = pg_ddl::table_design(&s, "d_rollback", "items")
        .await
        .unwrap();
    let mut design = original.clone();
    // Every row gets 7, so the unique index on it fails after the column
    // was added and `price` changed type: all of it must be undone.
    let mut extra = col("extra", "integer");
    extra.default = Some("7".into());
    design.columns.push(extra);
    design.columns[2].column_type = "integer".into();
    design.indexes.push(IndexDesign {
        original: None,
        name: "items_extra_u".into(),
        kind: IndexKind::Unique,
        parts: vec![IndexPart {
            column: "extra".into(),
            ..Default::default()
        }],
        using: None,
        comment: String::new(),
    });
    let run = pg_ddl::apply(
        &s,
        &SchemaChange::AlterTable {
            database: "d_rollback".into(),
            original: Box::new(original.clone()),
            design: Box::new(design),
            convert_charset: false,
        },
    )
    .await
    .unwrap();
    assert!(run.outcome.error.is_some(), "{}", run.sql);
    let now = pg_ddl::table_design(&s, "d_rollback", "items")
        .await
        .unwrap();
    assert_eq!(now, original, "nothing changed");
    // The session is usable afterwards (not stuck in an aborted transaction).
    let out = s.execute("SELECT count(*) FROM d_rollback.items", 0).await;
    assert!(out.error.is_none(), "{:?}", out.error);
}

#[tokio::test]
async fn views_functions_and_triggers() {
    let Some(s) = session_or_skip("d_obj").await else {
        return;
    };
    let save = |kind, original: Option<&str>, def: &str| SchemaChange::SaveObject {
        database: "d_obj".into(),
        object_kind: kind,
        original: original.map(Into::into),
        definition: def.into(),
    };
    apply_ok(
        &s,
        &save(
            ObjectKind::View,
            None,
            "CREATE VIEW d_obj.cheap AS SELECT id, name FROM d_obj.items WHERE price < 2",
        ),
    )
    .await;
    apply_ok(
        &s,
        &save(
            ObjectKind::Function,
            None,
            "CREATE FUNCTION d_obj.touch() RETURNS trigger LANGUAGE plpgsql AS $$
             BEGIN NEW.note := 'touched; ok'; RETURN NEW; END $$;",
        ),
    )
    .await;
    apply_ok(
        &s,
        &save(
            ObjectKind::Trigger,
            None,
            "CREATE TRIGGER items_touch BEFORE UPDATE ON d_obj.items
             FOR EACH ROW EXECUTE FUNCTION d_obj.touch()",
        ),
    )
    .await;
    apply_ok(
        &s,
        &save(
            ObjectKind::Procedure,
            None,
            "CREATE PROCEDURE d_obj.bump(n int) LANGUAGE sql AS $$ UPDATE d_obj.items SET price = price + n $$",
        ),
    )
    .await;

    let list = pg_ddl::objects(&s, "d_obj").await.unwrap();
    let mut found: Vec<(ObjectKind, String)> = list
        .objects
        .iter()
        .map(|o| (o.kind, o.name.clone()))
        .collect();
    found.sort_by_key(|(_, n)| n.clone());
    assert_eq!(
        found,
        [
            (ObjectKind::Procedure, "bump(IN n integer)".to_string()),
            (ObjectKind::View, "cheap".to_string()),
            (ObjectKind::Trigger, "items_touch".to_string()),
            (ObjectKind::Function, "touch()".to_string()),
        ]
    );
    assert!(list.event_scheduler.is_none());

    let out = s.execute("UPDATE d_obj.items SET price = 1 WHERE name = 'a'; SELECT note FROM d_obj.items WHERE name = 'a'", 10).await;
    assert!(out.error.is_none(), "{:?}", out.error);
    assert_eq!(out.results[1].rows[0][0], serde_json::json!("touched; ok"));

    let def = pg_ddl::definition(&s, "d_obj", ObjectKind::View, "cheap")
        .await
        .unwrap();
    assert!(
        def.definition.contains("CREATE OR REPLACE VIEW"),
        "{}",
        def.definition
    );
    let def = pg_ddl::definition(&s, "d_obj", ObjectKind::Function, "touch()")
        .await
        .unwrap();
    assert!(def.definition.contains("touched; ok"), "{}", def.definition);
    // Saving the loaded definition back works (OR REPLACE, no drop).
    apply_ok(
        &s,
        &save(ObjectKind::Function, Some("touch()"), &def.definition),
    )
    .await;
    let def = pg_ddl::definition(&s, "d_obj", ObjectKind::Trigger, "items_touch")
        .await
        .unwrap();
    assert!(
        def.definition.contains("BEFORE UPDATE"),
        "{}",
        def.definition
    );
    // Editing a trigger drops and re-creates it.
    apply_ok(
        &s,
        &save(
            ObjectKind::Trigger,
            Some("items_touch"),
            "CREATE TRIGGER items_touch BEFORE INSERT ON d_obj.items
             FOR EACH ROW EXECUTE FUNCTION d_obj.touch()",
        ),
    )
    .await;

    // A definition with a second statement is refused.
    let err = pg_ddl::plan(
        &s,
        &save(
            ObjectKind::View,
            None,
            "CREATE VIEW d_obj.v AS SELECT 1; DROP TABLE d_obj.items",
        ),
    )
    .await;
    assert!(err.is_err());

    for (kind, name) in [
        (ObjectKind::Trigger, "items_touch"),
        (ObjectKind::Function, "touch()"),
        (ObjectKind::Procedure, "bump(IN n integer)"),
        (ObjectKind::View, "cheap"),
    ] {
        apply_ok(
            &s,
            &SchemaChange::DropObject {
                database: "d_obj".into(),
                object_kind: kind,
                name: name.into(),
            },
        )
        .await;
    }
    assert!(
        pg_ddl::objects(&s, "d_obj")
            .await
            .unwrap()
            .objects
            .is_empty()
    );
}

#[tokio::test]
async fn creates_and_drops_schemas() {
    let Some(s) = session_or_skip("d_schema").await else {
        return;
    };
    s.execute("DROP SCHEMA IF EXISTS \"New Schema\" CASCADE", 0)
        .await;
    apply_ok(
        &s,
        &SchemaChange::CreateDatabase {
            name: "New Schema".into(),
            charset: None,
            collation: None,
        },
    )
    .await;
    let names: Vec<String> = s
        .list_databases()
        .await
        .unwrap()
        .into_iter()
        .map(|d| d.name)
        .collect();
    assert!(names.iter().any(|n| n == "New Schema"), "{names:?}");
    apply_ok(
        &s,
        &SchemaChange::DropDatabase {
            name: "New Schema".into(),
        },
    )
    .await;
}
